      await welcome.getByRole('button',{name:'Commencer',exact:true}).click();
      await page.reload();
      assert.equal(await page.getByRole('region',{name:'Bienvenue sur CHKPT',exact:true}).count(),0);
      await openSettings(page);
      await page.getByRole('button',{name:'Revoir les 3 étapes CHKPT',exact:true}).click();
      await welcome.getByRole('button',{name:'Passer',exact:true}).click();
      await page.getByRole('button',{name:'Carte',exact:true}).click();
      const search = page.getByRole('searchbox',{name:'Rechercher un établissement',exact:true});
      await search.fill('étoile cocody');
      await page.getByRole('status').filter({hasText:'1 lieu trouvé'}).waitFor();
      await capture('recherche-lieux-390.png');
      await search.fill('introuvable-xyz');
      await page.getByText(/Aucun lieu ne correspond/).waitFor();
      await search.fill('etoile');
      await page.getByRole('button',{name:'Détails',exact:true}).click();
      const venue=page.getByRole('dialog',{name:"Maquis L'Étoile d'Abidjan",exact:true});
      const reviews=venue.getByRole('region',{name:'Avis sur le lieu',exact:true});
      await reviews.getByText('Camille · personnage fictif',{exact:true}).waitFor();
      if (width === 390 && process.env.CHKPT_CAPTURE_DIR) await reviews.screenshot({path:path.join(process.env.CHKPT_CAPTURE_DIR,'avis-exemple-390.png')});
      assert.equal(await reviews.getByRole('radio').count(),5);
      assert.ok(await reviews.getByRole('button',{name:'Publier mon avis',exact:true}).isDisabled());
      await reviews.getByRole('radio',{name:'5 étoiles',exact:true}).focus();
      await page.keyboard.press('Space');
      const message=`Belle ambiance de démonstration ${width}.`;
      await reviews.getByRole('textbox',{name:'Votre commentaire',exact:true}).fill(message);
      await reviews.getByRole('button',{name:'Publier mon avis',exact:true}).click();
      await reviews.getByRole('status').getByText('Votre avis de démonstration est enregistré.',{exact:true}).waitFor();
      assert.equal(await reviews.getByRole('article').count(),1);
      await reviews.getByRole('radio',{name:'4 étoiles',exact:true}).focus();
      await page.keyboard.press('Space');
      await reviews.getByRole('button',{name:'Mettre à jour mon avis',exact:true}).click();
      await reviews.getByRole('article').getByLabel('4 étoiles sur 5',{exact:true}).waitFor();
      await reviews.scrollIntoViewIfNeeded();
      await capture('avis-lieu-390.png');
      await venue.getByRole('button',{name:'Fermer la fiche',exact:true}).click();
      await page.reload();
      await page.getByRole('button',{name:'Carte',exact:true}).click();
      await search.fill('etoile');
      await page.getByRole('button',{name:'Détails',exact:true}).click();
      await reviews.getByRole('article').getByText(message,{exact:true}).waitFor();
      await venue.getByRole('button',{name:'Fermer la fiche',exact:true}).click();
      await page.getByRole('button',{name:'Profil',exact:true}).click();
      const reward=page.getByRole('region',{name:'Ma récompense de démonstration',exact:true});
      await reward.getByText(/À débloquer/).waitFor();
      await page.getByRole('button',{name:'Valider ma présence physique',exact:true}).click();
      const check=page.getByRole('dialog',{name:'Check-in',exact:true});
      await check.getByRole('button',{name:/Maquis L'Étoile/}).click();
      await check.getByRole('button',{name:'Confirmer le check',exact:true}).click();
      await check.getByRole('heading',{name:'Visite simulée enregistrée !',exact:true}).waitFor();
      await check.getByRole('button',{name:'Plus tard (Terminer)',exact:true}).click();
      await page.getByRole('button',{name:'Profil',exact:true}).click();
      await reward.getByRole('button',{name:'Essayer l’utilisation fictive',exact:true}).click();
      await reward.getByRole('status').waitFor();
      await capture('recompense-390.png');
      await page.reload();
      await page.getByRole('button',{name:'Profil',exact:true}).click();
      await reward.getByText('Utilisation fictive enregistrée.',{exact:true}).waitFor();
      await page.getByText('1315 XP au total',{exact:true}).waitFor();
      await openSettings(page);
      await page.getByRole('button',{name:'Aperçu établissement · fictif',exact:true}).click();
      const business=page.getByRole('region',{name:'Aperçu établissement',exact:true});
      await business.getByText(/Toutes les statistiques ci-dessous sont fictives/).waitFor();
      await capture('apercu-etablissement-390.png');
      await business.getByRole('combobox').selectOption('plc_cocody_lounge');
      await business.getByRole('heading',{name:'Lagon Bleu Rooftop Lounge',exact:true}).waitFor();
      await business.getByRole('button',{name:'Retour au profil',exact:true}).click();
      await page.getByRole('button',{name:'Sortir',exact:true}).click();
      const filters=page.getByRole('region',{name:'Filtres des sorties',exact:true});
      const results=page.getByRole('region',{name:'Résultats des sorties',exact:true});
      await filters.getByRole('combobox',{name:'Catégorie de sortie',exact:true}).selectOption('bars');
      assert.equal(await results.getByRole('button').count(),1);
      await filters.getByRole('combobox',{name:'Distance maximale',exact:true}).selectOption('1000');
      assert.equal(await results.getByRole('button').count(),0);
      await filters.getByRole('combobox',{name:'Distance maximale',exact:true}).selectOption('5000');
      assert.equal(await results.getByRole('button').count(),1);
      await capture('sortir-filtres-390.png');
      await filters.getByRole('combobox',{name:'Catégorie de sortie',exact:true}).selectOption('restaurants');
      await filters.getByRole('combobox',{name:'Distance maximale',exact:true}).selectOption('10000');
      assert.equal(await results.getByRole('button').count(),1);
      await filters.getByRole('combobox',{name:'Catégorie de sortie',exact:true}).selectOption('clubs');
      await results.getByText(/Aucun établissement correspondant/).waitFor();
